#!/usr/bin/env node
/**
 * Toggle WORKSPACE_MEMBER_INVITE_EMAIL_ENABLED on family-service via compose overlay + recreate.
 * CarelinkAuth d7c80ef: flag is env-only (no per-family DB column); web overlay sets it true.
 */
import { execFile } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { assertCarelinkAuthRoot, resolveCarelinkAuthRoot } from './carelink-auth-compose.mjs';

const execFileAsync = promisify(execFile);

const COMPOSE_FILES = [
  'docker-compose.yml',
  'e2e/docker-compose.e2e.yml',
  'e2e/docker-compose.web.yml',
];

const OVERLAY_REL = 'e2e/e2e.invites-flag.runtime.yml';

/**
 * @param {boolean} enabled
 */
export async function recreateFamilyServiceInviteEmailEnabled(enabled) {
  const root = resolveCarelinkAuthRoot();
  assertCarelinkAuthRoot(root);

  const overlayPath = path.join(root, OVERLAY_REL);
  const yaml = [
    '# Generated by CarelinkWeb invites E2E — do not commit (gitignored in Auth if present).',
    'services:',
    '  family-service:',
    '    environment:',
    `      WORKSPACE_MEMBER_INVITE_EMAIL_ENABLED: "${enabled ? 'true' : 'false'}"`,
    '',
  ].join('\n');
  await writeFile(overlayPath, yaml, 'utf8');

  const argv = ['compose'];
  for (const file of COMPOSE_FILES) {
    argv.push('-f', path.join(root, file));
  }
  argv.push('-f', overlayPath, 'up', '-d', '--no-deps', 'family-service');

  await execFileAsync('docker', argv, {
    env: process.env,
    timeout: 180_000,
    maxBuffer: 4 * 1024 * 1024,
  });

  return { ok: true, mode: 'env', enabled };
}
